-- Postgres ยอมให้มี NULL ซ้ำกี่แถวก็ได้ในดัชนี unique ⇒ ผู้ใช้ที่ยังไม่ผูก
-- LINE (ซึ่งตอนนี้คือเกือบทุกคน) ไม่ได้รับผลกระทบ
--
-- ⚠ ถ้ามีค่าที่ไม่ใช่ NULL ซ้ำกันอยู่ migration นี้จะล้ม — ตั้งใจให้ล้ม
-- ตรวจก่อนลงด้วย:
--   SELECT line_user_id, count(*) FROM core.users
