-- Holiday แบบสะสม: สิทธิ์ของแต่ละเดือนใช้ได้กี่เดือน — HR/Boss ตั้งเองได้
--
-- ที่มา (ผู้ใช้ 19/11/2569): "ตอนนี้เหมือนล็อคอยู่ จะหมดสิทธิ์ถ้าเลย 3 เดือน อยากให้แก้ได้ว่าจะใช้ได้กี่เดือน"
-- เดิมเป็นค่าคงที่ HOLIDAY_VALID_MONTHS = 3 ในโค้ด · ค่าเริ่มต้น 3 ⇒ ทุกบริษัทเหมือนเดิมจนกว่าจะแก้
-- นับรวมเดือนที่ได้สิทธิ์ (3 = ของ ก.ค. ใช้ได้ถึงสิ้น ก.ย.) · ยอดคำนวณใหม่ทุกครั้ง ไม่ได้เก็บไว้
--   ⇒ ขยายเพิ่ม = สิทธิ์ที่เพิ่งหมดอายุไปกลับมาใช้ได้ · ลดลง = สิทธิ์เก่าหมดเร็วขึ้นทันที
ALTER TABLE workforce.leave_types
  ADD COLUMN IF NOT EXISTS holiday_valid_months integer NOT NULL DEFAULT 3
    CHECK (holiday_valid_months >= 1 AND holiday_valid_months <= 12);
