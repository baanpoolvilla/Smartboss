/**
 * สระบน/ล่าง + วรรณยุกต์ภาษาไทยที่ซ้อนกันผิดปกติ (24/11/2569 แจ้งบัค "อักษรแปลกปลอม")
 *
 * ชื่อที่มีไม้โทซ้ำติดกันหลายสิบตัว ("เซี้้้้้…ย" — กดค้างบนมือถือ) แสดงเป็นแท่งตัวอักษรสูงพุ่งทับเนื้อหาอื่น
 * เพราะเครื่องหมายพวกนี้ไม่มีความกว้างของตัวเอง ซ้อนขึ้นไปเรื่อย ๆ — ข้อความภาษาไทยปกติมีซ้อนไม่เกิน 2 ตัว
 * (สระบน + วรรณยุกต์ เช่น "กี้")
 *
 *  - เครื่องหมายที่ไม่มีตัวอักษรรองรับ (ต้นข้อความ/หลังเว้นวรรค/ขึ้นบรรทัด) → ตัดออก
 *    (24/11/2569 คอมเมนต์ขึ้นต้นด้วยไม้โท 29 ตัว ซ้อนเป็นแท่งพุ่งทับโพสต์ด้านบน)
 *  - เครื่องหมายเดียวกันซ้ำติดกัน → เหลือตัวเดียว
 *  - เครื่องหมายต่างกันเกิน 2 ตัวติดกัน → เก็บ 2 ตัวแรก
 * ข้อความปกติไม่เปลี่ยนเลย
 */
const MARK = "[\\u0E31\\u0E34-\\u0E3A\\u0E47-\\u0E4E]";
const SAME_REPEAT = new RegExp(`(${MARK})\\1+`, "g");
const TOO_MANY = new RegExp(`(${MARK}{2})${MARK}+`, "g");
const NO_BASE = new RegExp(`(^|\\s)${MARK}+`, "g");
const NO_BASE_AFTER_SPACE = new RegExp(`(\\s)${MARK}+`, "g");

/**
 * @param opts.midText ข้อความนี้อาจเป็นท่อนกลางคำ (ข้อความหนึ่งก้อนในช่องเขียนแบบจัดรูปแบบ ที่ตัวหนา/สีแบ่งคำเป็นหลายก้อน)
 *   — ไม่ตัดเครื่องหมายที่อยู่ต้นก้อน (ตัวอักษรรองรับอาจอยู่ก้อนก่อนหน้า) ตัดเฉพาะหลังเว้นวรรค
 */
export function tidyThaiMarks(text: string, opts?: { midText?: boolean }): string {
  if (!text) return text;
  return text
    .replace(opts?.midText ? NO_BASE_AFTER_SPACE : NO_BASE, "$1")
    .replace(SAME_REPEAT, "$1")
    .replace(TOO_MANY, "$1");
}
