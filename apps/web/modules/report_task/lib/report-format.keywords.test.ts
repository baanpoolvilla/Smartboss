import { describe, expect, it } from "vitest";
import { checkReportFormat, normalizeTopics, topicKeywords, topicLabel } from "./report-format";

// คำหลัก (16/11/2569 "ให้มันรู้พอแล้ว แต่ก็ไม่หลุดจนเกินไป")
const SET = [
  "🏁Common Report🏁",
  "วันนี้ส่งงานอะไร | ~ส่งงาน | ~ทำงานอะไร",
  "งานที่ล่าช้า ผิดพลาด ไม่เป็นไปตามแผน | ~ล่าช้า | ~ผิดแผน | ~งานค้าง",
  "ปัญหาและความเสี่ยง | ~ปัญหา | ~อุปสรรค",
  "วิธีแก้ไขและความรับผิดชอบ | ~วิธีแก้",
  "เรื่องที่ต้องการให้ Boss ตัดสินใจ | ~ตัดสินใจ",
];

describe("คำหลัก", () => {
  it("แยกชื่อกับคำหลัก — คำหลักไม่ใช่ชื่อ", () => {
    expect(topicLabel(SET[2]!)).toBe("งานที่ล่าช้า ผิดพลาด ไม่เป็นไปตามแผน");
    expect(topicKeywords(SET[2]!)).toEqual(["ล่าช้า", "ผิดแผน", "งานค้าง"]);
    expect(normalizeTopics([SET[2]!])[0]).toBe(SET[2]);
  });

  it("ชื่อใกล้เคียงบนบรรทัดหัวข้อ = ผ่าน", () => {
    const text = [
      "Common Report",
      "🟢 วันนี้ส่งงาน: ส่งแบบบ้าน A",
      "🟡 งานล่าช้า/ผิดแผน: รอช่างแอร์",
      "🟢 ปัญหาและอุปสรรค: ไม่มี",
      "🟢 วิธีแก้ไข: โทรตามช่าง",
      "🟢 เรื่องที่ต้องการให้ Boss ตัดสินใจ: ไม่มี",
    ].join("\n");
    const c = checkReportFormat(text, SET, true);
    expect(c.missing).toEqual([]);
    expect(c.ok).toBe(true);
  });

  it("คำหลักในเนื้อหายาว ๆ (ไม่มีสี ไม่ใช่บรรทัดหัวข้อ) ไม่นับ", () => {
    const text = [
      "Common Report",
      "🟢 วันนี้ส่งงานอะไร: ส่งแบบบ้าน A แล้ว ส่วนบ้าน B อาจจะล่าช้าเพราะฝนตกหนักทั้งวัน ต้องรอดูพรุ่งนี้อีกที",
      "🟢 ปัญหาและความเสี่ยง: ไม่มี",
      "🟢 วิธีแก้ไขและความรับผิดชอบ: -",
      "🟢 เรื่องที่ต้องการให้ Boss ตัดสินใจ: ไม่มี",
    ].join("\n");
    const c = checkReportFormat(text, SET, true);
    expect(c.missing).toEqual(["งานที่ล่าช้า ผิดพลาด ไม่เป็นไปตามแผน"]);
  });

  it("คำหลักต้องอยู่ช่วงต้นบรรทัด — ไม่ใช่ท้ายประโยคยาว", () => {
    const text = "🟡 ช่างแอร์มาไม่ได้เพราะรถเสียกลางทางระหว่างมาที่บ้าน งานเลยล่าช้า";
    expect(checkReportFormat(text, [SET[2]!], false).missing).toEqual(["งานที่ล่าช้า ผิดพลาด ไม่เป็นไปตามแผน"]);
  });

  it("บรรทัดเดียวมีหลายคำหลัก = หัวข้อที่คำหลักขึ้นก่อน", () => {
    const text = ["🟢 วิธีแก้ไขปัญหา: โทรตามช่าง", "🟢 ปัญหาและความเสี่ยง: ไม่มี"].join("\n");
    const c = checkReportFormat(text, [SET[3]!, SET[4]!], true);
    expect(c.missing).toEqual([]);
  });

  it("ไม่มีคำหลัก = เทียบชื่อแบบเดิม (รอบเดิมไม่เปลี่ยนพฤติกรรม)", () => {
    const c = checkReportFormat("🟡 งานล่าช้า/ผิดแผน: รอช่าง", ["งานที่ล่าช้า ผิดพลาด ไม่เป็นไปตามแผน"], true);
    expect(c.ok).toBe(false);
  });
});
