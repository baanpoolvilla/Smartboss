import { prisma } from "@smartboss/database";
import { notifyDuePmSchedules } from "@/modules/maintenance/data/cron";
(async () => {
  const { orgId } = await prisma.user.findUniqueOrThrow({ where: { id: "t-admin" }, select: { orgId: true } });
  const prop = await prisma.property.findFirstOrThrow({ where: { orgId, archivedAt: null } });
  const day = (n: number) => { const d = new Date(Date.now() + 7 * 3600e3 + n * 86_400_000).toISOString().slice(0, 10); return new Date(`${d}T23:59:59.999+07:00`); };
  const base = { orgId, propertyId: prop.id, createdBy: "t-admin", requiresExpense: false };
  const normal = await prisma.workOrder.create({ data: { ...base, code: "OVD-1", title: "ทดสอบเลยกำหนด ใบทั่วไป", assignedTo: "t-ton", ccUserIds: ["t-hr"], dueDate: day(-2) } });
  const notYet = await prisma.workOrder.create({ data: { ...base, code: "OVD-2", title: "ทดสอบยังไม่เลย", assignedTo: "t-ton", dueDate: day(0) } });
  const priv = await prisma.workOrder.create({ data: { ...base, code: "OVD-3", title: "ทดสอบส่วนตัวเลย 5 วัน", assignedTo: "t-admin", isPrivate: true, dueDate: day(-5) } });
  const ids = [normal.id, notYet.id, priv.id];
  await notifyDuePmSchedules();
  const ns = await prisma.notification.findMany({ where: { orgId, referenceId: { in: ids } }, select: { userId: true, title: true, referenceId: true } });
  const by = (id: string) => ns.filter((n) => n.referenceId === id);
  const c = (n: string, ok: boolean, d = "") => console.log(`${ok ? "PASS" : "FAIL"} | ${n}${d ? " | " + d : ""}`);
  c("ใบทั่วไปเลย 2 วัน → ผู้รับผิดชอบได้เตือน (CC ไม่ได้)", by(normal.id).length === 1 && by(normal.id)[0]!.userId === "t-ton", by(normal.id).map((n) => n.title).join());
  c("ใบที่ครบกำหนดวันนี้ ยังไม่เตือนเลยกำหนด", by(notYet.id).length === 0);
  c("ใบส่วนตัวเลย 5 วัน → เตือน (เดิมทุก 3 วันจะข้าม)", by(priv.id).length === 1 && by(priv.id)[0]!.userId === "t-admin", by(priv.id).map((n) => n.title).join());
  await prisma.notification.deleteMany({ where: { orgId, referenceId: { in: ids } } });
  await prisma.workOrder.deleteMany({ where: { orgId, id: { in: ids } } });
  process.exit(0);
})();
